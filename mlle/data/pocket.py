"""
"Pocket": a tiny synthetic language with a known probability distribution.

Why a synthetic language? Because for real text nobody knows the true distribution, so
there is no way to say how good a loss value is. Pocket is generated by a small
probabilistic grammar, which gives us three things real corpora cannot:

1. The exact entropy rate of the source. A language model's cross-entropy can approach
   this number but never beat it (Module 02), so we know what "fully trained" means.
2. A long-range dependency we control: subject-verb number agreement across a relative
   clause that contains a distractor noun ("the cats that chase the dog SLEEP").
   A bigram model cannot solve it; attention can (Modules 02, 05, 06).
3. Unlimited, license-free, perfectly reproducible data.

Grammar (probabilities in brackets):

    S        -> NP(n, subject) VP(n) " .\n"          n in {sg, pl} with [0.5, 0.5]
    NP(n, r) -> "the " [ADJ " " : 0.3] NOUN(n) [RC(n) : P_RC if r allows a relative clause]
    RC(n)    -> " that " VT(n) " " NP(m, no-RC)      m in {sg, pl} with [0.5, 0.5]
    VP(n)    -> " " VI(n)                 [0.4]
              | " " VT(n) " " NP(m, object)          [0.6], m in {sg, pl} with [0.5, 0.5]

Every word belongs to exactly one category and relative clauses cannot nest, so every
sentence has exactly one derivation. Therefore the probability of a sentence is the
product of the probabilities of the choices made while generating it, and
`sample_sentence` can return the exact log-probability.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass

NOUNS = [("cat", "cats"), ("dog", "dogs"), ("bird", "birds"), ("fox", "foxes"), ("robot", "robots"), ("child", "children")]
ADJECTIVES = ["small", "old", "red", "quick", "quiet"]
VERBS_INTRANSITIVE = [("sleeps", "sleep"), ("runs", "run"), ("sings", "sing"), ("waits", "wait")]
VERBS_TRANSITIVE = [("sees", "see"), ("likes", "like"), ("chases", "chase"), ("helps", "help")]

P_ADJ = 0.3
P_RC = 0.25
P_INTRANSITIVE = 0.4
SG, PL = 0, 1


@dataclass
class Sentence:
    text: str  # includes the trailing " .\n"
    logprob: float  # natural-log probability of this exact sentence under the grammar
    subject_number: int  # SG or PL
    has_rc: bool  # whether the subject carries a relative clause
    attractor_number: int | None  # number of the noun inside the subject's relative clause
    main_verb_index: int  # character offset where the main verb starts


class _Sampler:
    """Draws choices and accumulates their log-probabilities."""

    def __init__(self, rng: random.Random):
        self.rng = rng
        self.logprob = 0.0

    def flip(self, p: float) -> bool:
        hit = self.rng.random() < p
        self.logprob += math.log(p if hit else 1.0 - p)
        return hit

    def choice(self, items):
        self.logprob += -math.log(len(items))
        return self.rng.choice(items)


def _noun_phrase(s: _Sampler, number: int, allow_rc: bool):
    words = ["the"]
    if s.flip(P_ADJ):
        words.append(s.choice(ADJECTIVES))
    words.append(s.choice(NOUNS)[number])
    attractor = None
    has_rc = False
    if allow_rc and s.flip(P_RC):
        has_rc = True
        attractor = PL if s.flip(0.5) else SG
        inner, _, _ = _noun_phrase(s, attractor, allow_rc=False)
        words += ["that", s.choice(VERBS_TRANSITIVE)[number]] + inner
    return words, has_rc, attractor


def sample_sentence(rng: random.Random) -> Sentence:
    s = _Sampler(rng)
    number = PL if s.flip(0.5) else SG
    subject, has_rc, attractor = _noun_phrase(s, number, allow_rc=True)
    prefix = " ".join(subject) + " "
    if s.flip(P_INTRANSITIVE):
        predicate = [s.choice(VERBS_INTRANSITIVE)[number]]
    else:
        verb = s.choice(VERBS_TRANSITIVE)[number]
        obj_number = PL if s.flip(0.5) else SG
        obj, _, _ = _noun_phrase(s, obj_number, allow_rc=True)
        predicate = [verb] + obj
    text = prefix + " ".join(predicate) + " .\n"
    return Sentence(text, s.logprob, number, has_rc, attractor, len(prefix))


def generate_corpus(num_sentences: int, seed: int = 0) -> str:
    rng = random.Random(seed)
    return "".join(sample_sentence(rng).text for _ in range(num_sentences))


def entropy_rate(num_samples: int = 20000, seed: int = 123) -> dict:
    """Monte-Carlo estimate of the source entropy.

    Sentences are independent, so by the renewal-reward theorem the entropy rate per
    character is E[-log p(sentence)] / E[len(sentence)].  Returned in nats and bits."""
    rng = random.Random(seed)
    total_nll, total_chars, total_words = 0.0, 0, 0
    for _ in range(num_samples):
        sent = sample_sentence(rng)
        total_nll += -sent.logprob
        total_chars += len(sent.text)
        total_words += len(sent.text.split()) + 1  # words, the full stop, and the newline that ends the sentence
    return {
        "nats_per_sentence": total_nll / num_samples,
        "chars_per_sentence": total_chars / num_samples,
        "nats_per_char": total_nll / total_chars,
        "bits_per_char": total_nll / total_chars / math.log(2),
        "nats_per_word": total_nll / total_words,  # per token of mlle.foundations.ngram.WordTokenizer
    }


def agreement_items(num_items: int = 200, seed: int = 7, with_attractor: bool | None = True):
    """Minimal pairs for testing number agreement.

    Each item is (prefix, correct_verb, wrong_verb). The prefix ends right before the main
    verb. With `with_attractor=True` the subject carries a relative clause whose noun has
    the OPPOSITE number, so a model that just copies the number of the nearest noun gets
    the item wrong."""
    rng = random.Random(seed)
    items = []
    while len(items) < num_items:
        number = rng.choice([SG, PL])
        noun = rng.choice(NOUNS)[number]
        if with_attractor:
            attractor = rng.choice(NOUNS)[1 - number]
            rc_verb = rng.choice(VERBS_TRANSITIVE)[number]
            prefix = f"the {noun} that {rc_verb} the {attractor} "
        else:
            prefix = f"the {noun} "
        verb = rng.choice(VERBS_INTRANSITIVE)
        items.append((prefix, verb[number], verb[1 - number]))
    return items
